import {build} from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'motion-src/catalog.json'),'utf8'));
await build({entryPoints:[path.join(root,'motion-src/pwa-adapter.js')],bundle:true,format:'iife',globalName:'GymMotion',minify:true,target:'es2020',outfile:path.join(root,'gym-motion-v54.js'),legalComments:'eof'});
fs.writeFileSync(path.join(root,'gym-motion-catalog-v54.js'),'/* Exact catalog bindings for the approved shared GymTracker mannequin. */\nwindow.GYM_CUSTOM_MOTIONS='+JSON.stringify(catalog)+';\n');
const assets=path.join(root,'assets/gym-motion');fs.mkdirSync(assets,{recursive:true});fs.copyFileSync(path.join(root,'node_modules/three/LICENSE'),path.join(assets,'THREE-LICENSE.txt'));
console.log(`Built local motion runtime and ${catalog.length} exact catalog bindings. No CDN required.`);
